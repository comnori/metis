import { electron } from './test-electron.mjs';
import executablePath from 'electron';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.resolve(import.meta.dirname, '..'), run = path.join(root, '.pre04-runs', `m1-05-${Date.now()}`);
const fixture = path.join(run, 'workspace'); await mkdir(path.join(fixture, 'docs'), { recursive: true });
const source = '= Search\n:topic: release\n\n[[needle-anchor]]\n== Needle section\n\nNeedle body';
await writeFile(path.join(fixture, 'note.adoc'), source);
await writeFile(path.join(fixture, 'docs/other.adoc'), '= Other\n\nSecond document');
const env = { ...process.env, METIS_USER_DATA: path.join(run, 'profile') }; delete env.ELECTRON_RUN_AS_NODE;
const packaged = process.argv[2];
const app = await electron.launch({ executablePath: packaged || executablePath, args: packaged ? ['--smoke'] : [path.join(root, 'apps/desktop'), '--smoke'], env });
const checks = [];
try {
  const page = await app.firstWindow(); page.on('dialog', dialog => { void dialog.dismiss().catch(() => {}); });
  await app.evaluate(({ dialog }, fixture) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [fixture] }); dialog.showMessageBoxSync = () => 1; }, fixture);
  await page.getByRole('button', { name: '폴더 열기', exact: true }).first().click();
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent === '빠른 열기' && !button.disabled));
  await page.keyboard.press('ControlOrMeta+p');
  const modal = page.locator('dialog'), query = modal.getByRole('searchbox', { name: '검색어' });
  await query.fill('docs/');
  await modal.getByRole('button', { name: /파일 · other.adoc/ }).click();
  await page.getByRole('heading', { name: 'docs/other.adoc', exact: true }).waitFor(); checks.push('keyboard quick open filters nested file paths');
  await page.keyboard.press('ControlOrMeta+Shift+f'); await query.fill('Needle body');
  await modal.getByRole('button', { name: /본문 · note.adoc/ }).filter({ hasText: 'note.adoc:7' }).click();
  await page.getByRole('heading', { name: 'note.adoc', exact: true }).waitFor();
  await page.waitForFunction(() => window.getSelection()?.anchorNode?.textContent?.includes('Needle body')); checks.push('body snippet opens matching source line');
  await page.getByRole('button', { name: '검색', exact: true }).click();
  await modal.getByLabel('검색 모드').selectOption('symbols'); await query.fill('topic');
  await modal.getByRole('button', { name: /속성 · topic/ }).filter({ hasText: 'note.adoc:2' }).waitFor();
  await query.fill('Needle'); await modal.getByRole('button', { name: /절 · Needle section/ }).waitFor();
  await modal.getByRole('button', { name: /앵커 · needle-anchor/ }).waitFor(); checks.push('semantic attribute, section and anchor results');
  await query.fill('not-present'); await modal.getByRole('status').filter({ hasText: '결과가 없습니다' }).waitFor(); checks.push('empty results distinguish completed search');
  await modal.getByLabel('검색 모드').selectOption('text'); await query.fill('Needle body');
  await modal.getByRole('button', { name: /본문 · note.adoc/ }).waitFor();
  await writeFile(path.join(fixture, 'note.adoc'), '= Changed\n\nExternal saved content');
  await modal.getByRole('button', { name: /본문 · note.adoc/ }).click();
  await page.locator('footer').filter({ hasText: '검색 이후 원본이 변경' }).waitFor();
  const editor = page.locator('.editor-panel:not([hidden]) .cm-content');
  assert.ok((await editor.textContent()).includes('External saved content')); checks.push('changed source reloads clean tab without stale line jump');
  await editor.click(); await page.keyboard.press('ControlOrMeta+a'); await page.keyboard.insertText('= Unsaved buffer\n\nKeep my changes');
  await writeFile(path.join(fixture, 'note.adoc'), source);
  await page.getByRole('button', { name: '검색', exact: true }).click(); await query.fill('Needle body');
  await modal.getByRole('button', { name: /본문 · note.adoc/ }).click();
  await page.locator('footer').filter({ hasText: '미저장 편집을 유지' }).waitFor();
  assert.ok((await editor.textContent()).includes('Keep my changes')); checks.push('saved-file result preserves dirty tab and warns about location');
  await page.getByRole('button', { name: '검색', exact: true }).click(); await query.fill('Needle');
  await modal.getByRole('button', { name: '검색 취소', exact: true }).dispatchEvent('click');
  await modal.getByRole('status').filter({ hasText: '검색을 취소했습니다' }).waitFor();
  await modal.getByRole('button', { name: '다시 검색', exact: true }).click();
  await modal.getByRole('button', { name: /본문 · note.adoc/ }).first().waitFor(); checks.push('cancel and restart search');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].showInactive());
  await page.screenshot({ path: path.join(run, 'window.png') });
  await page.keyboard.press('Escape');
  const responses = await page.evaluate(async () => {
    const opened = await window.metis.openWorkspace({ requestId: 'search-session' }); if (!opened.ok) throw new Error('open failed');
    const scope = { workspaceId: opened.value.workspaceId, workspaceEpoch: opened.value.workspaceEpoch };
    const first = window.metis.searchDocuments({ ...scope, requestId: 'old-search', query: 'Needle', mode: 'symbols', caseSensitive: false });
    const latest = window.metis.searchDocuments({ ...scope, requestId: 'new-search', query: 'Second', mode: 'text', caseSensitive: false });
    const malformed = window.metis.searchDocuments({ ...scope, requestId: 'bad-search', query: 'x', mode: 'text', caseSensitive: false, root: 'C:/' });
    return Promise.all([first, latest, malformed]);
  });
  assert.equal(responses[0].ok, false); assert.equal(responses[0].error.code, 'CANCELLED');
  assert.equal(responses[1].ok, true); assert.equal(responses[1].value.hits[0].relativePath, 'docs/other.adoc');
  assert.equal(responses[2].error.code, 'INVALID_REQUEST'); checks.push('superseded worker request cancels and unsafe IPC payload rejects');
  assert.equal(await readFile(path.join(fixture, 'note.adoc'), 'utf8'), source); checks.push('search never writes source');
  await writeFile(path.join(run, 'results.json'), JSON.stringify({ platform: process.platform, packaged: !!packaged, checks }, null, 2));
  console.log(JSON.stringify({ run, checks }, null, 2));
} catch (error) {
  console.error('Completed checks:', checks);
  throw error;
} finally { await app.evaluate(({ dialog }) => { dialog.showMessageBoxSync = () => 1; }).catch(() => {}); await app.close(); }
