import { uiCommand } from './ui-command.mjs';
import { _electron as electron } from 'playwright';
import executablePath from 'electron';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.resolve(import.meta.dirname, '..'), run = path.join(root, '.pre04-runs', `m2-02-${Date.now()}`), fixture = path.join(run, 'workspace');
await mkdir(fixture, { recursive: true });
const files = { 'a.adoc': '= A\n\nxref:shared.adoc[]', 'b.adoc': '= B\n\nxref:shared.adoc[]', 'shared.adoc': '= Shared\n\nBody' };
for (const [name, text] of Object.entries(files)) await writeFile(path.join(fixture, name), text);
const env = { ...process.env, METIS_USER_DATA: path.join(run, 'profile') }; delete env.ELECTRON_RUN_AS_NODE;
const packaged = process.argv[2], checks = [];
const app = await electron.launch({ executablePath: packaged || executablePath, args: packaged ? ['--smoke'] : [path.join(root, 'apps/desktop'), '--smoke'], env });
try {
  const page = await app.firstWindow(); page.on('dialog', dialog => { void dialog.dismiss().catch(() => {}); });
  await app.evaluate(({ dialog }, fixture) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [fixture] }); dialog.showMessageBoxSync = () => 1; }, fixture);
  await page.getByRole('button', { name: '폴더 열기', exact: true }).first().click();
  await page.getByRole('button', { name: '≡a.adoc', exact: true }).click();
  await uiCommand(page, '관계 탐색');
  const modal = page.getByRole('dialog', { name: '작업 공간 관계' }), related = modal.getByRole('region', { name: '관련 문서', exact: true });
  await related.getByRole('button', { name: '관련 문서: b.adoc', exact: true }).click();
  const detail = related.getByRole('region', { name: '관련 근거' });
  await detail.getByText('공통 참조 대상: shared.adoc', { exact: true }).waitFor();
  await detail.getByRole('button', { name: '근거 원문: a.adoc:3', exact: true }).waitFor();
  await detail.getByRole('button', { name: '근거 원문: b.adoc:3', exact: true }).waitFor();
  checks.push('common target shows both original declarations');
  await related.getByRole('button', { name: '관계 그래프', exact: true }).click();
  const node = related.getByRole('button', { name: '그래프 문서: b.adoc', exact: true });
  assert.equal(await node.getAttribute('aria-pressed'), 'true');
  const before = await node.getAttribute('style'); await node.focus(); await node.press('ArrowRight');
  assert.notEqual(await node.getAttribute('style'), before);
  await related.getByRole('button', { name: '관련 목록', exact: true }).click();
  assert.equal(await related.getByRole('button', { name: '관련 문서: b.adoc', exact: true }).getAttribute('aria-pressed'), 'true');
  await related.getByRole('button', { name: '관계 그래프', exact: true }).click();
  assert.notEqual(await node.getAttribute('style'), before);
  await related.getByRole('button', { name: '그래프 배치 초기화', exact: true }).click();
  assert.equal(await node.getAttribute('style'), before);
  checks.push('list and graph preserve selection and local keyboard layout; reset restores layout');
  await node.click({ trial: true }); const box = await node.boundingBox(); assert.ok(box);
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 45, box.y + box.height / 2 + 30, { steps: 5 }); await page.mouse.up();
  assert.notEqual(await node.getAttribute('style'), before);
  for (const [name, text] of Object.entries(files)) assert.equal(await readFile(path.join(fixture, name), 'utf8'), text);
  assert.equal(await page.evaluate(() => window.getSelection()?.toString()), '');
  checks.push('pointer drag changes layout without writing source or selecting surrounding text');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].showInactive()); await page.screenshot({ path: path.join(run, 'related-graph.png') });
  await detail.getByRole('button', { name: '근거 원문: b.adoc:3', exact: true }).click();
  await page.getByRole('heading', { name: 'b.adoc', exact: true }).waitFor();
  const editor = page.locator('.editor-panel:not([hidden]) .cm-content'); await editor.click(); await page.keyboard.press('ControlOrMeta+End'); await page.keyboard.insertText('\nUnsaved');
  await uiCommand(page, '관계 탐색'); await modal.getByLabel('대상 문서').selectOption('a.adoc');
  await related.getByRole('button', { name: '관련 문서: b.adoc', exact: true }).click();
  await detail.getByRole('button', { name: '근거 원문: b.adoc:3', exact: true }).click();
  assert.ok((await editor.textContent()).includes('Unsaved')); checks.push('evidence navigation opens source and preserves dirty buffer');
  await uiCommand(page, '관계 탐색'); await modal.getByLabel('대상 문서').selectOption('a.adoc');
  await related.getByRole('button', { name: '관련 문서: b.adoc', exact: true }).click();
  await related.getByRole('button', { name: '관계 그래프', exact: true }).click();
  await writeFile(path.join(fixture, 'b.adoc'), '= B\n\nNo reference');
  await page.waitForFunction(() => { const region = document.querySelector('section[aria-label="관련 문서"]'); return region?.querySelector('[aria-label="그래프 문서: shared.adoc"]') && !region.querySelector('[aria-label="그래프 문서: b.adoc"]') && !region.querySelector('[aria-label="관련 근거"]'); }, undefined, { timeout: 15000 });
  checks.push('automatic rebuild removes stale related node and evidence while retaining graph mode');
  await writeFile(path.join(run, 'results.json'), JSON.stringify({ packaged: !!packaged, checks }, null, 2)); console.log(JSON.stringify({ run, checks }, null, 2));
} catch (error) { console.error('Completed:', checks); throw error; }
finally { await app.evaluate(({ dialog }) => { dialog.showMessageBoxSync = () => 1; }).catch(() => {}); await app.close(); }
