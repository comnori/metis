import { electron } from './test-electron.mjs';
import executablePath from 'electron';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { uiCommand } from './ui-command.mjs';

const root = path.resolve(import.meta.dirname, '..');
const run = path.join(root, '.pre04-runs', `diagram-navigation-${Date.now()}`), fixture = path.join(run, 'workspace');
await mkdir(fixture, { recursive: true });
await writeFile(path.join(fixture, 'note.adoc'), '= Diagram controls\n\n[mermaid]\n----\nflowchart LR\n A[Start] --> B[End]\n----\n\n[d2]\n----\na: Client\nb: Server\na -> b: request\nlayers: { detail: { c: Details } }\n----\n\n== Paragraphs\n\n' + Array.from({ length: 35 }, (_, i) => `Paragraph ${i + 1}. ${'Scroll position should stay while editing. '.repeat(8)}\n`).join('\n'));
const env = { ...process.env, METIS_USER_DATA: path.join(run, 'profile') }; delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ executablePath, args: [path.join(root, 'apps/desktop'), '--smoke'], env });
let page;
try {
  page = await app.firstWindow(); page.setDefaultTimeout(30000);
  page.on('dialog', dialog => { void dialog.dismiss().catch(() => {}); });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await app.evaluate(({ BrowserWindow, dialog }, fixture) => { BrowserWindow.getAllWindows()[0].showInactive(); dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [fixture] }); dialog.showMessageBoxSync = () => 1; }, fixture);
  await page.getByRole('button', { name: '폴더 열기', exact: true }).first().click();
  await page.getByRole('button', { name: '≡note.adoc', exact: true }).click();
  const settings = page.getByRole('dialog', { name: '설정' });
  const auto = settings.getByRole('checkbox', { name: '미리보기 위치 자동 맞춤', exact: true });
  const openSettings = async () => { await uiCommand(page, '설정'); await settings.getByRole('button', { name: '미리보기', exact: true }).click(); };
  await openSettings(); assert.equal(await auto.isChecked(), true); await auto.uncheck();
  await settings.getByRole('button', { name: '직전 변경 되돌리기', exact: true }).click(); assert.equal(await auto.isChecked(), true);
  await auto.uncheck(); await settings.getByRole('button', { name: '닫기', exact: true }).click();
  await page.reload(); await openSettings(); assert.equal(await auto.isChecked(), false);
  await settings.getByRole('button', { name: '이 범주 기본값 복원', exact: true }).click(); assert.equal(await auto.isChecked(), true);
  await settings.getByRole('button', { name: '직전 변경 되돌리기', exact: true }).click(); assert.equal(await auto.isChecked(), false);
  await settings.getByRole('button', { name: '닫기', exact: true }).click();
  await page.getByRole('button', { name: '≡note.adoc', exact: true }).click();
  await page.getByRole('button', { name: '분할', exact: true }).click();
  const frame = page.locator('iframe[title="AsciiDoc 미리보기"]'), preview = page.frameLocator('iframe[title="AsciiDoc 미리보기"]');
  const mermaid = preview.locator('.metis-mermaid'), d2 = preview.locator('[data-d2-board="root"]');
  const controls = section => section.getByRole('group', { name: '다이어그램 보기 조절', exact: true });
  const transform = section => section.locator('.metis-diagram-viewport>svg').evaluate(svg => svg.style.transform);
  await controls(d2).waitFor();
  for (const section of [mermaid, d2]) {
    await controls(section).getByRole('button', { name: '다이어그램 확대', exact: true }).click();
    assert.ok((await transform(section)).includes('scale(1.25)'));
    const area = section.getByRole('group', { name: '다이어그램 이동 영역', exact: true });
    await area.scrollIntoViewIfNeeded(); const rect = await area.boundingBox();
    await page.mouse.move(rect.x + 50, rect.y + 50); await page.mouse.down();
    await page.mouse.move(rect.x + 110, rect.y + 80, { steps: 5 }); await page.mouse.up();
    assert.ok((await transform(section)).includes('translate(60px, 30px)'));
    await area.focus(); await page.keyboard.press('ArrowRight'); assert.ok((await transform(section)).includes('translate(90px, 30px)'));
    await page.mouse.move(rect.x + 100, rect.y + 60); await page.keyboard.down('Control'); await page.mouse.wheel(0, -120); await page.keyboard.up('Control');
    await page.waitForFunction(() => [...document.querySelector('iframe').contentDocument.querySelectorAll('.metis-diagram-tools output')].some(output => output.textContent === '159%'));
    assert.ok(!(await transform(section)).includes('scale(1.25)'));
    await controls(section).getByRole('button', { name: '다이어그램 화면에 맞춤', exact: true }).click();
    assert.equal(await transform(section), 'translate(0px, 0px) scale(1)');
    await controls(section).getByRole('button', { name: '다이어그램 확대', exact: true }).click();
  }
  await preview.locator('details[data-d2-board]>summary').click();
  const detail = preview.locator('details[data-d2-board]'); await controls(detail).getByRole('button', { name: '다이어그램 확대', exact: true }).click();
  assert.ok((await transform(detail)).includes('scale(1.25)'));
  await preview.locator('details[data-d2-board]>summary').click();
  await frame.evaluate(frame => { frame.dataset.stable = 'yes'; frame.contentWindow.scrollTo(0, 700); });
  await page.waitForFunction(() => document.querySelector('iframe').contentWindow.scrollY === 700);
  const editor = page.locator('.editor-panel:not([hidden]) .cm-content');
  await editor.focus(); await page.keyboard.press('ControlOrMeta+End');
  assert.equal(await frame.evaluate(frame => frame.contentWindow.scrollY), 700);
  assert.equal(await frame.getAttribute('data-stable'), 'yes');
  await page.keyboard.insertText('\nEdited while automatic alignment is off.\n');
  await preview.getByText('Edited while automatic alignment is off.', { exact: false }).waitFor();
  await page.waitForFunction(() => document.querySelector('iframe').contentWindow.scrollY === 700);
  assert.ok((await transform(mermaid)).includes('scale(1.25)')); assert.ok((await transform(d2)).includes('scale(1.25)'));
  const output = path.join(run, 'zoom-independent.pdf');
  await app.evaluate(({ dialog }, output) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: output }); }, output);
  await page.getByRole('button', { name: 'PDF 다운로드', exact: true }).click();
  await page.getByRole('status').filter({ hasText: /^PDF를 저장했습니다\.$/ }).waitFor();
  assert.equal((await readFile(output)).subarray(0, 4).toString(), '%PDF');
  assert.ok((await transform(mermaid)).includes('scale(1.25)'));
  await page.getByRole('button', { name: '문서 정보', exact: true }).click();
  await page.getByRole('button', { name: '편집 위치와 맞추기', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('iframe').contentWindow.scrollY > 2000);
  await frame.evaluate(frame => { frame.dataset.stable = 'yes'; });
  await openSettings(); await auto.check(); await settings.getByRole('button', { name: '닫기', exact: true }).click();
  assert.equal(await frame.getAttribute('data-stable'), 'yes', 'alignment preference must not rebuild the frame');
  await editor.focus(); await page.keyboard.press('ControlOrMeta+Home');
  await page.waitForFunction(() => document.querySelector('iframe').contentWindow.scrollY < 3);
  await page.getByRole('button', { name: '문서 정보', exact: true }).click();
  assert.deepEqual(errors, []); await page.screenshot({ path: path.join(run, 'controls.png') });
  console.log(JSON.stringify({ run, output, checks: ['auto-alignment persistence, undo, reset and immediate toggle', 'scroll remains fixed through cursor movement and edits when disabled', 'manual alignment while disabled', 'Mermaid and D2 zoom, drag, keyboard, wheel and fit', 'collapsed D2 boards have independent controls', 'view state retained across prose edits', 'PDF exports full diagrams independently of zoom'] }, null, 2));
} catch (error) {
  console.error(error); if (page) { console.error((await page.locator('body').innerText()).slice(-2500)); await page.screenshot({ path: path.join(run, 'failed.png') }).catch(() => {}); }
  throw error;
} finally { await app.close(); }
